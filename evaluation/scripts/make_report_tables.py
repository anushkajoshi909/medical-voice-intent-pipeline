#!/usr/bin/env python3
"""Generate evaluation/reports/tables/results_summary.md from the run folders (summary.json files).

Groups: B0 (Ludyga); FIRST RUN (folders 2026-11-03_*_final_r*); SECOND RUN (folders 2026-11-04_*_final500_r* and 2026-11-05_*_final4000_r*).
DeepSeek and gpt-oss run with 500 and with 4000 completion tokens.
Numbers are mean +- SD over the repetitions. Counting rules: evaluation/evaluation.md section 5.
"""
import glob
import json
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GROUPS = [
    ("B0 Ludyga grammar", "runs/2026-11-03_B0-ludyga*"),
    ("First run: Llama 3.3 70B", "runs/2026-11-03_meta-llama*_final_r*"),
    ("First run: Gemma 4 26B", "runs/2026-11-03_google*_final_r*"),
    ("First run: gpt-oss-120b (500 tok)", "runs/2026-11-03_openai_gpt-oss-120b_final_r*"),
    ("First run: gpt-oss-120b (4000 tok)", "runs/2026-11-03_openai_gpt-oss-120b__maxtok4000_final_r*"),
    ("First run: DeepSeek V4.1 Flash (500 tok)", "runs/2026-11-03_deepseek-ai_DeepSeek-V4.1-Flash_final_r*"),
    ("First run: DeepSeek V4.1 Flash (4000 tok)", "runs/2026-11-03_deepseek-ai_DeepSeek-V4.1-Flash__maxtok4000_final_r*"),
    ("Second run: Llama 3.3 70B", "runs/2026-11-04_meta-llama*_final500_r*"),
    ("Second run: Gemma 4 26B", "runs/2026-11-04_google*_final500_r*"),
    ("Second run: gpt-oss-120b (500 tok)", "runs/2026-11-04_openai*_final500_r*"),
    ("Second run: gpt-oss-120b (4000 tok)", "runs/2026-11-05_openai*_final4000_r*"),
    ("Second run: DeepSeek V4.1 Flash (500 tok)", "runs/2026-11-04_deepseek*_final500_r*"),
    ("Second run: DeepSeek V4.1 Flash (4000 tok)", "runs/2026-11-05_deepseek*_final4000_r*"),
]


def load(pattern):
    return [json.load(open(d + "/summary.json")) for d in sorted(glob.glob(str(ROOT / pattern)))]


def ms(vals, nd=1):
    vals = [v for v in vals if v is not None]
    if not vals:
        return "n/a"
    sd = st.stdev(vals) if len(vals) > 1 else 0.0
    return f"{st.mean(vals):.{nd}f} ± {sd:.{nd}f}"


out = ["# Results summary (generated by scripts/make_report_tables.py)", "",
       "243 commands (130 valid, 113 invalid), mean ± SD over the repetitions. All values in percent unless noted.", "",
       "| System | runs | valid accepted | valid → clarification | valid rejected | invalid wrongly accepted | precision | F1 | accuracy (strict) | action accuracy | LLM error rate |",
       "|---|---|---|---|---|---|---|---|---|---|---|"]
for name, pat in GROUPS:
    runs = load(pat)
    if not runs:
        continue
    if name.startswith("B0"):
        h = runs[0]["all_items"]
        out.append(f"| {name} | 1 | {h['valid_recall_pct']} | {h['valid_clarification_rate_pct']} | {h['false_rejection_rate_pct']} | "
                   f"{h['false_acceptance_rate_pct']} | {h['precision_pct']} | {h['f1_pct']} | {h['accuracy_strict_pct']} | n/a | n/a |")
        b = runs[0]["ludyga_198_only"]
        out.append(f"| ↳ B0 on Ludyga's 198 sentences only | 1 | {b['valid_recall_pct']} | – | {b['false_rejection_rate_pct']} | "
                   f"{b['false_acceptance_rate_pct']} | {b['precision_pct']} | {b['f1_pct']} | {b['accuracy_strict_pct']} | n/a | n/a |")
        continue
    g = lambda k: ms([r["hybrid"][k] for r in runs])
    out.append(f"| {name} | {len(runs)} | {g('valid_recall_pct')} | {g('valid_clarification_rate_pct')} | {g('false_rejection_rate_pct')} | "
               f"{g('false_acceptance_rate_pct')} | {g('precision_pct')} | {g('f1_pct')} | {g('accuracy_strict_pct')} | "
               f"{ms([r['action_accuracy_pct'] for r in runs])} | {ms([r['llm_error_rate_pct'] for r in runs])} |")

out += ["", "## LLM alone (no ANTLR, ontology, type check) versus the full pipeline — FINAL runs", "",
        "| Model | valid accepted: LLM alone | valid accepted: pipeline | wrongly accepted: LLM alone | wrongly accepted: pipeline |", "|---|---|---|---|---|"]
for name, pat in GROUPS:
    if not name.startswith("FINAL"):
        continue
    runs = load(pat)
    out.append(f"| {name[7:]} | {ms([r['llm_only_B2']['valid_recall_pct'] for r in runs])} | {ms([r['hybrid']['valid_recall_pct'] for r in runs])} | "
               f"{ms([r['llm_only_B2']['false_acceptance_rate_pct'] for r in runs])} | {ms([r['hybrid']['false_acceptance_rate_pct'] for r in runs])} |")

out += ["", "## Latency per command in seconds — FINAL runs (remote LLM endpoint; depends on load and time of day)", "",
        "| Model | end-to-end median | end-to-end p95 | end-to-end mean | LLM call median | slowest non-LLM stage (max over commands, ms) | cold-start ontology index build |", "|---|---|---|---|---|---|---|"]
for name, pat in GROUPS:
    if not name.startswith("FINAL"):
        continue
    runs = load(pat)
    metas = [json.load(open(d + "/meta.json")) for d in sorted(glob.glob(str(ROOT / pat)))]
    e = [r["latency"]["end_to_end"] for r in runs]
    s2 = [r["latency"]["stage2"] for r in runs]
    rest = [1000 * max(r["latency"][s]["max_s"] for s in ("stage1", "stage3", "stage4", "stage5", "stage6") if s in r["latency"]) for r in runs]
    out.append(f"| {name[7:]} | {ms([x['median_s'] for x in e], 2)} | {ms([x['p95_s'] for x in e], 2)} | {ms([x['mean_s'] for x in e], 2)} | "
               f"{ms([x['median_s'] for x in s2], 2)} | {ms(rest, 0)} | {metas[0].get('cold_start_first_ontology_lookup_s')} |")
out += ["", "Reference (Ludyga 2024, Sect. 7.3): grammar-only average response time 195 ms; acceptance criterion ≤ 1 s."]
dest = ROOT / "reports" / "tables" / "results_summary.md"
dest.write_text("\n".join(out) + "\n")
print(f"-> {dest}")
